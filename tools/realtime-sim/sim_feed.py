"""
PTE Real-Time Availability Simulator (synthetic Hobart CBD fixture)
===================================================================

WHY THIS EXISTS
---------------
Parking Truth Engine needs to prove that a *live* availability feed, a moving
GPS position, and the frontend contract all work together BEFORE any real
municipal feed is legally wired up.

Real Hobart feeds exist (Park My Ride / parking-occupancy.hobartcity.com.au)
but they are:
  * not published as a documented public API,
  * behind bot protection (parkmyride.au -> Azure Front Door WAF), and
  * explicitly "may not reuse or republish ... without written consent from
    the City" (hobartcity.com.au Live parking availability map page).

So this simulator emits a feed with the SAME SHAPE, CADENCE and FAILURE MODES
as a real sensor network, using geometry that is clearly labelled SYNTHETIC.
Nothing here is authoritative and nothing here may be presented as real Hobart
occupancy.

WHAT IT EMITS
-------------
  GET /api/health            source-health record (PTE shape: FRESH/STALE/...)
  GET /api/carparks.json     off-street occupancy (real capacities, synthetic counts)
  GET /api/bays.geojson      on-street bays + live status (GeoJSON FeatureCollection)
  GET /api/snapshot.json     compact combined snapshot, one HTTP round trip
  GET /api/bay/<bay_id>      single bay detail incl. occupiedSince
  GET /stream                Server-Sent Events: arrival/departure ticks
  GET /api/meta.json         simulator config + provenance/disclaimer

Cadence defaults to a 15 s tick, matching the published Park My Ride sensor
refresh rate. Use --tick for other cadences and --speed to run simulated time
faster than wall-clock.

STDLIB ONLY. Python 3.8+. No dependencies to install.

    python3 sim_feed.py                       # 0.0.0.0:8090, 15 s tick
    python3 sim_feed.py --port 8080 --speed 20
    python3 sim_feed.py --tick 5 --seed 42
"""

